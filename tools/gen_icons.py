def fetch(slug: str) -> str | None:
    for template in SOURCES:
        try:
            req = urllib.request.Request(template.format(slug),
                                         headers={"User-Agent": "Mozilla/5.0"})
            svg = urllib.request.urlopen(req, timeout=30).read().decode()
            m = re.search(r'\sd="([^"]+)"', svg)
            if m:
                return m.group(1)
        except Exception:
            continue
    return None


def main() -> int:
    icons: dict[str, str] = {}
    for key, slug in BRANDS.items():
        d = fetch(slug)
        if not d:
            print(f"FALHOU: {key} ({slug})", file=sys.stderr)
            return 1
        icons[key] = d
        print(f"  {key}: {len(d)} chars")
    icons.update(UI)

    out = [
        "<!-- GERADO por tools/gen_icons.py — não edite à mão.",
        "     Marcas das lojas: simple-icons (CC0 1.0, https://simple-icons.org).",
        "     Glifos de UI: paths estilo Material Symbols (Apache 2.0), viewBox 24x24.",
        "     Vetores em vez de emoji: emoji viram quadrados/glifos errados conforme a fonte. -->",
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
    ]
    for key, d in icons.items():
        out.append(f'    <PathGeometry x:Key="Icon{key}" Figures="{d}"/>')
    out.append("</ResourceDictionary>")

    path = Path(__file__).resolve().parent.parent / "src" / "Assets" / "Icons.xaml"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"\n{path}: {len(icons)} ícones")
    return 0


